// Per-game overrides for RC Revenge Pro (SLUS-20153), applied during loadELF.
//
// The game's file layer (FMFileFetchSectors) reads through a 96-sector cache
// aligned to multiples of 96 sectors, so it requests sectors outside the file
// it opened. The runtime's sceCdSearchFile hands out per-file pseudo sector
// numbers that cannot satisfy those reads. Here we report each file's real
// position on the disc and serve all reads from the ISO, as the hardware does.

