#!/usr/bin/env python3
"""Writes decomp/src/zlib_corpus.inc: deflate streams for the random test of the game's zlib (decomp/src/zlib_fuzz.cpp).

Each stream has a window size (9 to 12 bits, so a window fits the test's scratch area), a zlib header or none, a kind of
content and a way of compressing it, so that stored, fixed-Huffman and dynamic-Huffman blocks, many small blocks, runs,
sync and full flush points, preset dictionaries and empty streams are all there. Deterministic: run it again to get the same file.
"""
import random
import sys
import zlib

rng = random.Random(0x5a1b)
WORDS = ["car", "track", "turbo", "lap", "race", "RC", "revenge", "pro", "the", "of", "boost", "nitro", "tyre", "grip", "wall",
         "jump", "ramp", "level", "cup", "bronze", "silver", "gold", "pickup", "bomb", "shield", "0123", "4567", "89ab"]


def text(n):
    out = bytearray()
    while len(out) < n:
        out += rng.choice(WORDS).encode()
        out += rng.choice([b" ", b" ", b", ", b"\n", b"-", b"_"])
    return bytes(out[:n])


def noise(n):
    return bytes(rng.randrange(256) for _ in range(n))


def runs(n):
    out = bytearray()
    while len(out) < n:
        out += bytes([rng.choice([0, 0, 0xff, 0x41, rng.randrange(256)])]) * rng.randrange(1, 700)
    return bytes(out[:n])


def structured(n):
    # 32-bit little-endian words that count and repeat, like the game's tables
    out = bytearray()
    v = rng.randrange(1000)
    while len(out) < n:
        v += rng.choice([0, 1, 1, 4, 16, 0x100])
        out += (v & 0xffffffff).to_bytes(4, "little")
    return bytes(out[:n])


def mixed(n):
    out = bytearray()
    while len(out) < n:
        out += rng.choice([text, noise, runs, structured])(rng.randrange(20, 600))
    return bytes(out[:n])


MAKERS = {"text": text, "noise": noise, "runs": runs, "struct": structured, "mixed": mixed}


def compress(data, wbits, raw, level, strategy, memlevel, flushes, zdict=None):
    kwargs = {}
    if zdict is not None and not raw:
        kwargs["zdict"] = zdict
    c = zlib.compressobj(level, zlib.DEFLATED, -wbits if raw else wbits, memlevel, strategy, **kwargs)
    out = bytearray()
    pos = 0
    for cut in flushes:
        out += c.compress(data[pos:cut])
        out += c.flush(zlib.Z_SYNC_FLUSH if (cut & 1) else zlib.Z_FULL_FLUSH)
        pos = cut
    out += c.compress(data[pos:])
    out += c.flush(zlib.Z_FINISH)
    return bytes(out)


blob = bytearray()
entries = []


def add(data, wbits, raw, level=6, strategy=zlib.Z_DEFAULT_STRATEGY, memlevel=8, flushes=(), zdict=None):
    comp = compress(data, wbits, raw, level, strategy, memlevel, flushes, zdict)
    assert len(comp) <= 3800, len(comp)
    off = len(blob)
    blob.extend(comp)
    doff = len(blob)
    if zdict:
        blob.extend(zdict)
    entries.append((wbits, 1 if raw else 0, off, len(comp), doff if zdict else 0, len(zdict) if zdict else 0, len(data)))


# empty and tiny
for raw in (0, 1):
    add(b"", 12, raw)
    add(b"a", 10, raw)
    add(b"ab", 9, raw, level=0)
    add(b"aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa", 9, raw)
# the kinds, with each way of compressing them
plans = []
for kind in ("text", "noise", "runs", "struct", "mixed"):
    for wbits in (9, 10, 11, 12):
        plans.append((kind, wbits))
for kind, wbits in plans:
    n = rng.choice([200, 700, 1500, 2400, 3300])
    data = MAKERS[kind](n)
    raw = rng.random() < 0.3
    level = rng.choice([1, 3, 6, 9])
    strategy = rng.choice([0, 0, 1, 2, 3, 4])
    memlevel = rng.choice([1, 2, 4, 8, 9])
    flushes = sorted(rng.sample(range(1, n), rng.choice([0, 0, 1, 2, 3])))
    add(data, wbits, raw, level, strategy, memlevel, tuple(flushes))
# stored blocks (level 0), with and without flushes, and one that is a header, a stored block and the check
for wbits in (9, 12):
    for raw in (0, 1):
        data = mixed(rng.choice([100, 900, 3000]))
        add(data, wbits, raw, level=0, flushes=tuple(sorted(rng.sample(range(1, len(data)), 2))))
# fixed-Huffman streams
for wbits in (9, 11):
    for raw in (0, 1):
        add(text(rng.choice([150, 1200, 2800])), wbits, raw, level=6, strategy=zlib.Z_FIXED)
# many small dynamic blocks
for wbits in (9, 12):
    add(mixed(3000), wbits, 0, level=6, memlevel=1)
    add(text(3000), wbits, 1, level=9, memlevel=1)
# preset dictionaries
for wbits in (9, 10, 12):
    zdict = text(rng.choice([40, 300, 1 << (wbits - 1)]))
    data = zdict[:100] + text(500) + zdict[20:200] + text(300)
    add(data, wbits, 0, level=6, zdict=zdict)
    add(MAKERS["mixed"](1200) + zdict[:60], wbits, 0, level=9, zdict=zdict, flushes=(400,))

with open("decomp/src/zlib_corpus.inc", "w") as f:
    f.write("// Generated by tools/gen_zlib_corpus.py: deflate streams for zlib_fuzz.cpp. Do not edit.\n")
    f.write("// Stream: window bits, raw (no zlib header), offset and length in the blob, dictionary offset and length, bytes it inflates to.\n")
    f.write("struct CorpusStream { uint8_t wbits, raw; uint32_t offset, length, dictOffset, dictLength, outLength; };\n")
    f.write("static const CorpusStream kCorpus[] = {\n")
    for e in entries:
        f.write("    {%d, %d, %d, %d, %d, %d, %d},\n" % e)
    f.write("};\nstatic const uint8_t kCorpusBlob[] = {")
    for i, b in enumerate(blob):
        if i % 24 == 0:
            f.write("\n    ")
        f.write("%d," % b)
    f.write("\n};\n")
print(len(entries), "streams", len(blob), "bytes", file=sys.stderr)
