#!/usr/bin/env python3
"""Writes the per-version address headers the native code is compiled against.

Usage: gen_addrs.py <elf> <recompiled output dir> <out dir> [<reference elf> <changed_functions.txt>]
  USA: tools/gen_addrs.py ../disc/SLUS_201.53 output decomp/generated/usa
  EU:  tools/gen_addrs.py ../disc_eu/SLES_500.77 output_eu decomp/generated/eu ../disc/SLUS_201.53 \
           decomp/generated/eu/changed_functions.txt

Writes into <out dir>:
  rc_addrs.h  namespace rc::sym: the address of every symbol of the executable (functions, objects and named labels;
              not compiler labels) as constexpr uint32_t, named by its key (tools/rcelf.py) made an identifier ('.'
              becomes '_', a repeated name's '#n' becomes '__n'), plus the section starts (sec_text, sec_data, ...),
              image_end (_end) and the literal pool entries the native code reads (lit4_<usa address>, see below).
  rc_fns.h    namespace rc::fns: per recompiled function (as named in <recompiled output dir>/ps2_recompiled_functions.h,
              without its _0x<address> suffix) its address, its recompiled function and whether it behaves as the
              reference version's (false for the functions listed in changed_functions.txt). The RC_DECOMP_FN* macros
              take the function by this name and do not register a native whose function changed.

The .lit4 section (float literals, read $gp-relative, no symbols) is one word shorter in the Europe executable, so its
entries are not at a fixed offset. A lit4 entry is named lit4_<its USA address> and placed by rcelf.lit4_map (the
values aligned word by word, checked against every read in the code of the functions that are the same in both). An
entry that is not in this version gets 0xffffffc0: only functions that changed read it, and their natives are not
registered here. For USA itself the names are the addresses.
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import rcelf  # noqa: E402

SKIP_PREFIXES = ('$L', 'gcc2_compiled', '__gnu_compiled')


# Names the C and C++ headers define as macros: such a symbol is written with a trailing underscore (errno_).
MACRO_NAMES = {'errno', 'stdin', 'stdout', 'stderr', 'assert', 'offsetof', 'setjmp', 'longjmp', 'va_start', 'va_end',
               'va_arg', 'va_copy', 'NULL', 'EOF', 'isnan', 'isinf', 'isfinite', 'signbit', 'fpclassify', 'isnormal',
               'getc', 'putc', 'getchar', 'putchar', 'alloca', 'unix', 'linux', 'major', 'minor', 'makedev'}


def ident(key):
    name = re.sub(r'[^A-Za-z0-9_]', '_', key.replace('#', '__'))
    return name + '_' if name in MACRO_NAMES else name


def recompiled_functions(outdir):
    out = {}
    text = open(os.path.join(outdir, 'ps2_recompiled_functions.h')).read()
    for m in re.finditer(r'^void (\w+)_0x([0-9a-f]+)\(', text, re.M):
        out.setdefault(int(m.group(2), 16), []).append(m.group(1))
    return out


def main():
    elf_path, recomp_dir, outdir = sys.argv[1:4]
    elf = rcelf.Elf(elf_path)
    ref = rcelf.Elf(sys.argv[4]) if len(sys.argv) > 4 else None
    changed = set()
    if len(sys.argv) > 5:
        for line in open(sys.argv[5]):
            if line.strip() and not line.startswith('#'):
                changed.add(line.split('\t')[0])
    os.makedirs(outdir, exist_ok=True)
    name = os.path.basename(elf_path)
    lines = [f'// Generated by tools/gen_addrs.py from {name}: the address of every symbol, as rc::sym::<key>.',
             '// Native code names addresses through these (see NOTES.md, "Decompilation"), so it compiles for every version.',
             '#pragma once', '#include <cstdint>', '', 'namespace rc::sym {']
    seen = {}
    for s in sorted(elf.placed, key=lambda s: s.index):
        if s.name.startswith(SKIP_PREFIXES):
            continue
        n = ident(s.key)
        if n in seen:
            if seen[n] != s.value:
                sys.exit(f'{s.key}: identifier {n} already used')
            continue
        seen[n] = s.value
        lines.append(f'inline constexpr uint32_t {n} = {s.value:#x}u;')
    for s in elf.symbols:
        if s.name in ('_end', '_gp', '_fbss', '_edata', '_ftext', '_etext'):
            n = ident(s.key)
            if n not in seen:
                seen[n] = s.value
                lines.append(f'inline constexpr uint32_t {n} = {s.value:#x}u;')
    lines.append('')
    lines.append('// Section starts and ends.')
    for sec in ('.text', '.vutext', '.data', '.rodata', '.lit4', '.sdata', '.sbss', '.bss'):
        s = elf.section[sec]
        lines.append(f'inline constexpr uint32_t sec_{sec[1:]} = {s.addr:#x}u, sec_{sec[1:]}_end = {s.end:#x}u;')
    lines.append(f'inline constexpr uint32_t image_end = {elf.section[".bss"].end:#x}u;')
    lines.append('')
    lines.append('// .lit4 entries, named by their address in the USA executable.')
    if ref is None:
        lit = elf.section['.lit4']
        for a in range(lit.addr, lit.end, 4):
            lines.append(f'inline constexpr uint32_t lit4_{a:06x} = {a:#x}u;')
    else:
        pairs = rcelf.lit4_map(ref, elf)
        lit = ref.section['.lit4']
        for a in range(lit.addr, lit.end, 4):
            if a in pairs:
                lines.append(f'inline constexpr uint32_t lit4_{a:06x} = {pairs[a]:#x}u;')
            else:
                # Read only by functions that changed in this version, whose natives are not registered here.
                lines.append(f'inline constexpr uint32_t lit4_{a:06x} = 0xffffffc0u; // not in this version')
    lines.append('} // namespace rc::sym')
    open(os.path.join(outdir, 'rc_addrs.h'), 'w').write('\n'.join(lines) + '\n')

    # Recompiled functions, by name.
    funcs = recompiled_functions(recomp_dir)
    by_addr = {}
    for f in elf.functions:
        by_addr.setdefault(f.value, []).append(f)
    out = [f'// Generated by tools/gen_addrs.py from {name} and {recomp_dir}/ps2_recompiled_functions.h:',
           '// each recompiled function by name, for the RC_DECOMP_FN* macros (decomp/rc_decomp.h).',
           '#pragma once', '#include "ps2_recompiled_functions.h"', '', 'namespace rc {',
           'struct FnInfo', '{', '    uint32_t address;',
           '    void (*original)(uint8_t *, R5900Context *, PS2Runtime *);',
           '    bool sameAsReference; // false: this version\'s function differs from the USA one (version_diff.py)',
           '};', '} // namespace rc', '', 'namespace rc::fns {']
    stems = {}
    for addr, names in sorted(funcs.items()):
        for full in names:
            stems.setdefault(full, []).append(addr)
    skipped = 0
    for stem, addrs in sorted(stems.items(), key=lambda kv: kv[1][0]):
        for n, addr in enumerate(addrs):
            syms = by_addr.get(addr, [])
            key = syms[0].key if syms else None
            if key is None:
                skipped += 1  # entry_<address> rows with no symbol: never registered
                continue
            same = 'false' if key in changed else 'true'
            ident_name = stem if len(addrs) == 1 else f'{stem}__{n}'
            out.append(f'inline constexpr FnInfo {ident_name}{{{addr:#x}u, &::{stem}_0x{addr:x}, {same}}};')
    out.append('} // namespace rc::fns')
    open(os.path.join(outdir, 'rc_fns.h'), 'w').write('\n'.join(out) + '\n')
    print(f'{outdir}: {len(seen)} symbols, {len(stems)} recompiled names ({skipped} without a symbol), '
          f'{sum(1 for k in changed)} changed')


if __name__ == '__main__':
    main()
