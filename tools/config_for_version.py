#!/usr/bin/env python3
"""Writes the PS2Recomp config of another version of the game from the USA one (config.toml).

Usage: config_for_version.py <usa config> <usa elf> <other elf> <other function map> <other output dir> <out config>
       e.g. tools/config_for_version.py config.toml game/usa/disc/SLUS_201.53 game/eu/disc/SLES_500.77 \
                functions_eu.csv output_eu config_eu.toml

Changes input, output and ghidra_output (written relative to the folder of <out config>, from which the recompiler is
run), and moves every "name@0xaddress" entry (stubs, untracked_stubs, skip) to the
address of the same symbol in the other executable (tools/rcelf.py's symbol keys). Fails if a name does not match the
symbol found there.
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import rcelf  # noqa: E402


def main():
    src, elf_a, elf_b, fmap, outdir, dst = sys.argv[1:7]
    a, b = rcelf.Elf(elf_a), rcelf.Elf(elf_b)
    m = rcelf.VersionMap(a, b)
    text = open(src).read()

    def move(match):
        name, address = match.group(1), int(match.group(2), 16)
        at = [s for s in a.symbols_at(address) if s.kind == 'FUNC']
        candidates = [s for s in at if s.name == name] or at  # stub names can differ from the symbol (exit, _exit)
        if not candidates:
            sys.exit(f'{name}@{address:#x}: no such function symbol in {elf_a}')
        target = b.by_key[candidates[0].key]
        return f'"{name}@0x{target.value:08X}"'

    text, count = re.subn(r'"([^"@]+)@0x([0-9A-Fa-f]+)"', move, text)
    root = os.path.abspath(os.path.dirname(dst) or '.')

    def rel(path):
        return os.path.relpath(os.path.abspath(path), root)

    def setting(key, value):
        nonlocal text
        text = re.sub(rf'^{key} = .*$', f'{key} = "{value}"', text, count=1, flags=re.M)

    setting('input', rel(elf_b))
    setting('output', rel(outdir))
    setting('ghidra_output', rel(fmap))
    text = text.replace('# Auto-generated by ExportPS2Functions.java',
                        f'# Generated by tools/config_for_version.py from {os.path.basename(src)}, which was\n'
                        '# auto-generated by ExportPS2Functions.java', 1)
    open(dst, 'w').write(text)
    print(f'{count} stub addresses moved; wrote {dst}')


if __name__ == '__main__':
    main()
