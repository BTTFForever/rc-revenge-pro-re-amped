#!/usr/bin/env python3
"""Which of a version's changed functions (decomp/generated/<version>/changed_functions.txt, tools/version_diff.py) run
native in that version: a native written for both versions (RC_VERSION_VARIANT(Name) in its file) is registered there;
any other native of a changed function is not, and the version's recompiled function runs instead.

Usage (from fork/): tools/variant_status.py [eu]      writes decomp/generated/<version>/variant_status.txt
                    tools/variant_status.py --check    exit 1 if a changed function is not native (lists them)
"""
import glob
import re
import sys


def main():
    args = [a for a in sys.argv[1:] if not a.startswith('--')]
    version = args[0] if args else 'eu'
    sources = glob.glob('decomp/*.cpp') + glob.glob('decomp/src/*.cpp') + glob.glob('overrides/*.cpp')
    text = {p: open(p).read() for p in sources}
    rows, missing = [], []
    for line in open(f'decomp/generated/{version}/changed_functions.txt'):
        if line.startswith('#') or not line.strip():
            continue
        key, category = line.split('\t')[:2]
        name = key.split('#')[0]
        registered = [p for p, t in text.items() if re.search(r'RC_DECOMP_[A-Z_]*\(\s*' + re.escape(name) + r'\s*[,)]', t)]
        variant = [p for p, t in text.items() if re.search(r'^RC_VERSION_VARIANT\(' + re.escape(name) + r'\)', t, re.M)]
        where = registered[0] if registered else '-'
        status = 'native' if registered and variant else ('recompiled (native not a variant)' if registered else 'recompiled (no native)')
        if status != 'native':
            missing.append(name)
        rows.append(f'{key}\t{category}\t{status}\t{where}')
    if '--check' in sys.argv:
        for name in missing:
            print(name)
        return 1 if missing else 0
    with open(f'decomp/generated/{version}/variant_status.txt', 'w') as f:
        f.write('# Generated by tools/variant_status.py: each changed function (changed_functions.txt) and what runs for it in\n')
        f.write(f'# the {version} build (key, category, native or recompiled, the native\'s file).\n')
        f.write('\n'.join(rows) + '\n')
    print(f'{len(rows) - len(missing)} of {len(rows)} changed functions native in {version}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
